import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

// Optional: point PLAYWRIGHT_MODULE at an already installed playwright/index.mjs.
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(process.env.PLAYWRIGHT_MODULE).href : 'playwright');
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1050 } });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await mkdir('.demo-qa', { recursive: true });
const button = name => page.getByRole('button', { name, exact: true });
const click = name => button(name).click();
try {
  await page.goto('http://127.0.0.1:5173');
  await page.getByRole('heading', { name: '嗨，今天的你还好吗？' }).waitFor();
  await page.screenshot({ path: '.demo-qa/desktop.png', fullPage: true });
  await click('开始情绪签到 ↗');
  await page.locator('#dialog [data-mood="anxious"]').click();
  await page.locator('#intensity').fill('8');
  await page.locator('#note').fill('明天有数学考试，我有些紧张。');
  await click('记录此刻，看看推荐 ↗');
  assert.match(await page.locator('.summary').textContent(), /先稳一稳/);
  await click('试试这个练习 ↗');
  await click('我想试试 ↗');
  await click('下一步 →');
  await click('开始计时');
  await page.waitForFunction(() => document.querySelector('#timer-value')?.textContent === '00:29');
  await click('暂停计时');
  const paused = await page.locator('#timer-value').textContent();
  await page.waitForTimeout(1100);
  assert.equal(await page.locator('#timer-value').textContent(), paused);
  await click('重置');
  assert.equal(await page.locator('#timer-value').textContent(), '00:30');
  await click('下一步 →');
  await click('完成，去复盘 →');
  await page.locator('#intensity').fill('6');
  await click('有一点帮助');
  await page.locator('#reflection').fill('看看窗外，感觉好一点。');
  await click('保存这一步 ✓');
  await click('看看我的记录 ↗');
  assert.equal(await page.locator('.full-record').count(), 4);
  await page.reload();
  await page.locator('nav [data-view="records"]').click();
  assert.equal(await page.locator('.full-record').count(), 4);
  await page.locator('.delete-button').first().click();
  await click('保留');
  assert.equal(await page.locator('.full-record').count(), 4);
  await page.locator('.delete-button').first().click();
  await click('确认删除');
  assert.equal(await page.locator('.full-record').count(), 3);
  for (const id of ['thought','plan']) {
    await page.locator('nav [data-view="exercises"]').click();
    await page.locator(`[data-exercise="${id}"]`).click();
    await click('我想试试 ↗');
    if(id === 'plan') {
      await click('下一步 →');
      assert.match(await page.locator('#dialog-title').textContent(), /选一个/);
      await click('整理明天的考试用品');
    } else await page.locator('#answer').fill('我担心一次考试决定全部。');
    await click('下一步 →');
    await page.locator('#answer').fill('我也有做得不错的时候。');
    await click('上一步');
    if(id === 'thought') assert.equal(await page.locator('#answer').inputValue(),'我担心一次考试决定全部。');
    else assert.equal(await page.locator('[data-choice].selected').count(),1);
    await click('下一步 →');
    assert.equal(await page.locator('#answer').inputValue(),'我也有做得不错的时候。');
    await click('下一步 →');
    await page.locator('#answer').fill('我可以先做一点准备。');
    await click('完成，去复盘 →');
    await click('暂时没感觉');
    await click('保存这一步 ✓');
    await click('回到空间');
  }
  await click('想法整理');
  assert.equal(await page.locator('.exercise-card').count(),1);
  await page.locator('nav [data-view="today"]').click();
  await click('开始情绪签到 ↗');
  await page.locator('#note').fill('我不想活了');
  await click('记录此刻，看看推荐 ↗');
  assert.equal(await page.locator('#dialog-title').textContent(),'你可以寻求身边的帮助');
  assert.equal(await page.locator('#dialog a[href="tel:120"]').count(),1);
  await click('关闭帮助页');
  // User text is displayed literally, never interpreted as markup.
  await click('开始情绪签到 ↗');
  await page.locator('#note').fill('<img src=x onerror=alert(1)>');
  await click('记录此刻，看看推荐 ↗');
  await click('关闭');
  await page.locator('nav [data-view="records"]').click();
  assert.match(await page.locator('.full-record').first().textContent(), /<img src=x onerror=alert\(1\)>/);
  assert.equal(await page.locator('.full-record img').count(),0);
  await click('本地数据说明');
  await click('清空所有本地记录');
  await click('确认清空');
  await page.reload();
  await page.locator('nav [data-view="records"]').click();
  assert.equal(await page.locator('.full-record').count(),0);
  assert.match(await page.locator('.empty').textContent(), /这里还没有记录/);
  // Corrupted local storage recovers to an empty state.
  await page.evaluate(() => localStorage.setItem('mind-island-demo-v1', '{broken'));
  await page.reload();
  assert.equal(await page.locator('.hero').count(),1);
  await page.setViewportSize({ width:390, height:844 });
  await click('寻求帮助');
  assert.equal(await page.locator('#dialog-title').textContent(),'你可以寻求身边的帮助');
  await click('关闭帮助页');
  await page.screenshot({ path: '.demo-qa/mobile.png', fullPage:true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  await click('开始情绪签到 ↗');
  await page.screenshot({ path: '.demo-qa/mobile-checkin.png', fullPage:true });
  assert.ok(await page.locator('#dialog').evaluate(el => el.getBoundingClientRect().width < window.innerWidth));
  assert.deepEqual(errors, []);
  console.log('PASS: check-in, recommendations, all exercises, timer, history, reload, delete/cancel, filters, safety branch, escaping, clear, corrupt storage, mobile layout, no JS errors.');
} finally { await browser.close(); }
